def semantic_mismatch(source, text):
    negative_source = any(marker in source for marker in ("无法", "不能", "不可", "不得", "禁止"))
    negative_target = any(marker in text for marker in ("ない", "ません", "不可", "禁止", "不能", "無効", "なし", "ず", "ぬ", "できな", "られな"))
    restore_target = any(marker in text for marker in ("回復", "復元", "戻", "再開", "補充", "返還"))
    save_target = any(marker in text for marker in ("セーブ", "保存", "ファイル", "アーカイブ", "記録"))
    return (
        ("回合" in source and any(marker in text for marker in ("回転", "回路", "逆転", "結束", "サイクル", "輪")))
        or ("回合" in source and "循环" not in source and "循環" in text)
        or ("回合" in source and "复合" not in source and "複合" in text)
        or ("档" in source and "存档" not in source and ("ファイル" in text or "ランキング" in text))
        or ("生命" in source and "人生" in text)
        or ("件拘束具" in source and "事件拘束具" in text)
        or ("上限" in source and "国境" in text)
        or ("自缚" in source and not ("自縛" in text or "自己拘束" in text or "自己結合" in text))
        or ("回合" in source and not any(marker in text for marker in ("ターン", "ラウンド")))
        or (negative_source and not negative_target)
        or ("恢复" in source and not restore_target)
        or ("存档" in source and not save_target)
        or ("最多" in source and not any(marker in text for marker in ("最大", "まで", "以下", "上限", "せいぜい", "のみ")))
        or ("至少" in source and not any(marker in text for marker in ("以上", "最低", "少なくとも")))
        or ("免费" in source and not any(marker in text for marker in ("無料", "コスト0", "無償")))
    )


