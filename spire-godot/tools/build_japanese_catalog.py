def protect(text):
    spans = []
    for kind, pattern in (("raw", TAG), ("raw", FORMAT), ("raw", NAMED), ("raw", SYMBOL)):
        for hit in pattern.finditer(text):
            if not any(hit.start() < end and hit.end() > start for start, end, _, _ in spans):
                spans.append((hit.start(), hit.end(), kind, hit.group()))
    spans.sort()
    output = []
    protected = []
    position = 0
    for start, end, _, raw in spans:
        output.append(text[position:start])
        token = TOKENS[len(protected)]
        output.append(token)
        protected.append((token, SPECIAL.get(raw, raw)))
        position = end
    output.append(text[position:])
    marked = "".join(output)
    for english, japanese in sorted(GLOSSARY.items(), key=lambda pair: len(pair[0]), reverse=True):
        pattern = re.compile(re.escape(english), re.I)
        while pattern.search(marked):
            if len(protected) >= len(TOKENS):
                raise ValueError(f"too many protected segments: {text[:80]}")
            token = TOKENS[len(protected)]
            marked = pattern.sub(token, marked, count=1)
            protected.append((token, japanese))
    return marked, protected


def restore(text, protected):
    text = text.replace("▁", " ").strip()
    for token, value in sorted(protected, key=lambda pair: len(pair[0]), reverse=True):
        pattern = re.compile(re.escape(token), re.I)
        text, count = pattern.subn(lambda _: value, text)
        if count != 1:
            raise ValueError(f"lost protected token {token}: {text}")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" +([、。！？，；：）」』】])", r"\1", text)
    text = re.sub(r"([（「『【]) +", r"\1", text)
    return text.strip()


def encode(processor, text):
    return ["zho_Hans", *processor.encode(text, out_type=str), "</s>"]


def decode(processor, tokens):
    tokens = list(tokens)
    if tokens and tokens[0] == "jpn_Jpan":
        tokens.pop(0)
    return processor.decode([token for token in tokens if token != "</s>"])


def translate_fragments(marked, protected, processor, translator):
    tokens = [token for token, _ in protected]
    pieces = re.split("(" + "|".join(map(re.escape, tokens)) + ")", marked)
    plain = [piece for piece in pieces if piece and piece not in tokens]
    encoded = [encode(processor, piece) for piece in plain]
    prefixes = [["jpn_Jpan"] for _ in encoded]
    results = translator.translate_batch(encoded, target_prefix=prefixes, beam_size=4, max_decoding_length=768) if encoded else []
    translated = iter(decode(processor, result.hypotheses[0]) for result in results)
    return "".join(piece if piece in tokens else (next(translated) if piece else "") for piece in pieces)


def segments(text):
    result = []
    for line in text.splitlines(keepends=True):
        newline = "\n" if line.endswith("\n") else ""
        body = line[:-1] if newline else line
        pieces = [part for part in re.split(r"(?<=[.!?;:。！？；：])(?=\s|$|[^A-Za-z0-9])", body) if part]
        if not pieces and body:
            pieces = [body]
        for piece in pieces:
            while len(piece) > 500:
                cut = max(piece.rfind(", ", 0, 500), piece.rfind(" ", 0, 500))
                cut = cut + 1 if cut > 0 else 500
                result.append(piece[:cut])
                piece = piece[cut:]
            if piece:
                result.append(piece)
        if newline:
            result.append(newline)
    return result or [text]


def translate_texts(texts, processor, translator):
    prepared = []
    units = []
    for text in texts:
        output = []
        for part in segments(text):
            if part == "\n" or not part.strip():
                output.append(part)
                continue
            leading = part[: len(part) - len(part.lstrip())]
            trailing = part[len(part.rstrip()) :]
            marked, protected = protect(part.strip())
            slot = len(units)
            output.append(slot)
            units.append({"marked": marked, "protected": protected, "leading": leading, "trailing": trailing})
        prepared.append(output)

    translated_units = []
    for start in range(0, len(units), 64):
        batch = units[start : start + 64]
        encoded = [encode(processor, unit["marked"]) for unit in batch]
        results = translator.translate_batch(
            encoded,
            target_prefix=[["jpn_Jpan"] for _ in encoded],
            beam_size=4,
            max_decoding_length=768,
        )
        for unit, result in zip(batch, results):
            translated = decode(processor, result.hypotheses[0])
            try:
                translated = restore(translated, unit["protected"])
            except ValueError:
                translated = restore(
                    translate_fragments(unit["marked"], unit["protected"], processor, translator),
                    unit["protected"],
                )
            translated_units.append(unit["leading"] + translated + unit["trailing"])

    results = []
    for output in prepared:
        results.append("".join(translated_units[part] if isinstance(part, int) else part for part in output))
    return results


def template_parameters(text):
    return sorted(NAMED.findall(text) + FORMAT.findall(text))


def ordered_parameters(source):
    parameters = []
    for pattern in (FORMAT, NAMED):
        parameters.extend((hit.start(), hit.end(), hit.group()) for hit in pattern.finditer(source))
    parameters.sort()
    return parameters


def legacy_target(source, text):
    parameters = ordered_parameters(source)
    for index, (_, _, raw) in enumerate(parameters):
        updated = text.replace(raw, "{p" + str(index) + "}", 1)
        if updated == text:
            raise ValueError(f"lost legacy parameter {raw}: {source} -> {text}")
        text = updated
    return text


def invalid_machine_translation(text):
    markers = ("ブラックリスト", "⁇", "�", "[PH", "ZXQ", "広島", "海外の反応", "ありがとうございました", "やってみよう", "ショウジョウ", "(笑)", "カードキャプターさくら", "この記事へのトラックバック", "カーディガン", "恐怖の根源", "自律師")
    return not text.strip() or any(marker in text for marker in markers) or REPEATED_OUTPUT.search(text) != None


def information_loss(source, text):
    source_visible = re.sub(r"[\s\W_]+", "", FORMAT.sub("", NAMED.sub("", source)), flags=re.UNICODE)
    target_visible = re.sub(r"[\s\W_]+", "", FORMAT.sub("", NAMED.sub("", text)), flags=re.UNICODE)
    if source_visible and not target_visible:
        return True
    return len(source_visible) >= 2 and len(target_visible) < len(source_visible) * 0.5


def literal_numbers_preserved(source, text):
    def values(value):
        value = FORMAT.sub("", NAMED.sub("", value))
        return re.findall(r"\d+(?:\.\d+)?", value)

    source_values = values(source)
    target_values = values(text)
    return all(target_values.count(value) >= source_values.count(value) for value in set(source_values))


